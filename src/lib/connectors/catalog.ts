/**
 * The connector catalog: every app a bot can be given access to, beyond the
 * built-ins in BUILTIN_CONNECTORS. Data only; runtime code decides how to connect.
 *
 * Conventions
 *  - `status` left out means "available". "beta" works with caveats; "soon" is
 *    listed honestly but can't be connected yet (its `via` may be empty).
 *  - `via` is ordered best first. An official MCP server that any new client can
 *    sign in to (dynamic or metadata-document registration) comes first. When the
 *    vendor's MCP needs a pre-registered app, an allowlisted client, an org admin's
 *    approval or a waitlist, Composio comes first and the MCP entry follows, so it
 *    works once Build-a-bot is registered with that vendor.
 *  - `verified: true` means the URL and auth method were confirmed from the vendor's
 *    own docs, repo or domain-verified registry entry on 2026-10-14.
 *  - Every `simpleIcon` slug exists in simple-icons@16. Brands that simple-icons
 *    doesn't ship (Microsoft, Slack, LinkedIn, Canva, Amazon, OpenAI...) use a letter.
 *  - Composio toolkit slugs come from Composio's generated slug list (2026-10-12).
 *
 * Sources and per-vendor notes: docs/research/connectors-2026-10-14.md
 */

import type { Capability, ConnectorDef, ConnectorVia, Effect, JobId, Risk } from "./types";

const cap = (id: string, label: string, effect: Effect, risk: Risk): Capability => ({ id, label, effect, risk });

const composio = (toolkit: string): ConnectorVia => ({ kind: "composio", toolkit });

/** An official remote MCP server (Streamable HTTP). */
const mcp = (url: string, auth: "oauth" | "none" = "oauth", verified = true): ConnectorVia => ({
  kind: "mcp",
  url,
  auth,
  verified,
});

/** An official remote MCP server the user connects by pasting a token. */
const mcpToken = (url: string, tokenLabel: string, tokenUrl?: string): ConnectorVia => ({
  kind: "mcp",
  url,
  auth: "bearer",
  tokenLabel,
  ...(tokenUrl ? { tokenUrl } : {}),
  verified: true,
});

/** The user pastes the address of an MCP server they run (Home Assistant, n8n, databases). */
const customMcp = (): ConnectorVia => ({ kind: "custom_mcp" });

