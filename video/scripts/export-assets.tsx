/**
 * Exports what the promo's stage needs from the app, so the video uses the product's own characters,
 * logo, fonts and motion: every avatar pose as inline SVG, the avatar stylesheet, and the two brand
 * fonts embedded as data URLs (the stage is opened from disk, where font files can't be fetched).
 *   npx tsx video/scripts/export-assets.tsx
 * Output: video/stage/generated/{assets.js,avatar.css,fonts.css}
 */
import fs from "node:fs";
import path from "node:path";
import { createElement, Fragment, type ComponentType } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { Avatar } from "../../src/components/avatar/Avatar";
import { LogoMark } from "../../src/components/brand/Logo";
import * as Lucide from "lucide-react";
import type { AvatarId, AvatarMood } from "../../src/lib/avatars";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const out = path.join(root, "video/stage/generated");

type Pose = { key: string; avatar: AvatarId; mood: AvatarMood; size: number };
const poses: Pose[] = [];
const full = (avatar: AvatarId, moods: AvatarMood[]) => moods.forEach((mood) => poses.push({ key: `${avatar}-${mood}`, avatar, mood, size: 200 }));
const small = (avatar: AvatarId, moods: AvatarMood[]) => moods.forEach((mood) => poses.push({ key: `${avatar}-${mood}-sm`, avatar, mood, size: 48 }));
full("otto", ["idle", "happy", "thinking", "working", "alert", "listening"]);
small("otto", ["idle", "happy", "thinking"]);
for (const a of ["blip", "nimbus", "sprout", "ember"] as const) full(a, ["idle", "happy"]);

// One render, so every useId (gradient ids) is unique across the page.
const tree = createElement(
  Fragment,
  null,
  ...poses.map((p) => createElement("div", { key: p.key, "data-k": p.key }, createElement(Avatar, { avatar: p.avatar, mood: p.mood, size: p.size, animated: true }))),
  createElement("div", { key: "logo", "data-k": "logo" }, createElement(LogoMark, { size: 48 })),
);
const html = renderToStaticMarkup(tree);

// Interface icons, from the same set the app uses (lucide).
const ICONS = ["Check", "Cake", "User", "Footprints", "Mail", "Leaf", "Lock", "Download", "Trash2", "Pencil", "Eye", "KeyRound", "Laptop", "Cpu", "ShieldCheck", "Code2", "Mic", "CloudOff", "Database", "Sparkles", "MessageCircle", "Brain", "Puzzle", "Repeat", "Paperclip", "ArrowUp", "ArrowRight", "FileJson", "CircleCheck", "Ban", "EyeOff", "Server"];
const icons: Record<string, string> = {};
for (const name of ICONS) {
  const C = (Lucide as unknown as Record<string, ComponentType<{ size?: number; strokeWidth?: number }>>)[name];
  icons[name] = renderToStaticMarkup(createElement(C, { size: 24, strokeWidth: 2 }));
}
const assets: Record<string, string> = {};
for (const m of html.matchAll(/<div data-k="([^"]+)">([\s\S]*?)<\/div>/g)) assets[m[1]] = m[2];
if (Object.keys(assets).length !== poses.length + 1) throw new Error(`expected ${poses.length + 1} assets, got ${Object.keys(assets).length}`);

const font = (file: string) => `data:font/woff2;base64,${fs.readFileSync(path.join(root, "node_modules/@fontsource-variable", file)).toString("base64")}`;
const fonts = `@font-face{font-family:"Inter Variable";font-style:normal;font-weight:100 900;font-display:block;src:url(${font("inter/files/inter-latin-wght-normal.woff2")}) format("woff2-variations");}
@font-face{font-family:"Bricolage Grotesque Variable";font-style:normal;font-weight:200 800;font-stretch:75% 100%;font-display:block;src:url(${font("bricolage-grotesque/files/bricolage-grotesque-latin-wght-normal.woff2")}) format("woff2-variations");}
`;

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "assets.js"), `// Generated by video/scripts/export-assets.tsx. Don't edit.\nwindow.BAB_ASSETS = ${JSON.stringify(assets)};\nwindow.BAB_ICONS = ${JSON.stringify(icons)};\n`);
fs.writeFileSync(path.join(out, "fonts.css"), fonts);
fs.copyFileSync(path.join(root, "src/components/avatar/avatar.css"), path.join(out, "avatar.css"));
console.log(`${Object.keys(assets).length} assets, fonts ${(fonts.length / 1024).toFixed(0)} KB`);
