/**
 * Generates src/lib/icons.generated.ts with only the simple-icons glyphs we use
 * (connector catalog, channels, model providers), so client bundles stay small.
 *   npx tsx scripts/gen-icons.ts
 */
import fs from "node:fs";
import path from "node:path";
import * as si from "simple-icons";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

async function main() {
  const slugs = new Set<string>();
  const { ALL_CONNECTORS } = await import("../src/lib/connectors/index");
  const { CHANNELS } = await import("../src/lib/channels/catalog");
  const { PROVIDERS, SUBSCRIPTIONS } = await import("../src/lib/models/catalog");
  const { MEETING_APPS } = await import("../src/lib/meetings/apps");
  for (const c of ALL_CONNECTORS) if (c.icon.simpleIcon) slugs.add(c.icon.simpleIcon);
  for (const c of CHANNELS) if (c.brand) slugs.add(c.icon);
  for (const p of PROVIDERS) if (p.icon.simpleIcon) slugs.add(p.icon.simpleIcon);
  for (const s of SUBSCRIPTIONS) if (s.icon.simpleIcon) slugs.add(s.icon.simpleIcon);
  for (const a of Object.values(MEETING_APPS)) if (a.icon.simpleIcon) slugs.add(a.icon.simpleIcon);
  for (const extra of ["nvidia", "claude", "googlegemini", "anthropic", "openrouter", "meta", "mistralai", "deepseek", "qwen", "huggingface"]) slugs.add(extra);

  const icons: Record<string, { title: string; hex: string; path: string }> = {};
  const missing: string[] = [];
  const table = si as unknown as Record<string, { title: string; hex: string; path: string; slug: string }>;
  const bySlug = new Map(Object.values(table).filter((v) => v && typeof v === "object" && "slug" in v).map((v) => [v.slug, v]));
  for (const slug of [...slugs].sort()) {
    const icon = bySlug.get(slug);
    if (!icon) {
      missing.push(slug);
      continue;
    }
    icons[slug] = { title: icon.title, hex: icon.hex, path: icon.path };
  }
  const out = `// Generated by scripts/gen-icons.ts from simple-icons (CC0). Do not edit by hand.\n// Brand names and logos belong to their owners; shown to indicate integrations.\nexport const BRAND_ICONS: Record<string, { title: string; hex: string; path: string }> = ${JSON.stringify(icons)};\n`;
  fs.writeFileSync(path.join(root, "src/lib/icons.generated.ts"), out);
  console.log(`Wrote ${Object.keys(icons).length} icons.${missing.length ? ` Missing: ${missing.join(", ")}` : ""}`);
}

main();
